package com.digitalasset.daml.lf
package testing.archive

import com.digitalasset.daml.lf.archive.{Dar, DarDecoder, DecodeV2}
import com.digitalasset.daml.lf.data.Ref.{DottedName, ModuleName, PackageId}
import com.digitalasset.daml.lf.language.LanguageVersion.{v2_1, v2_2, v2_3, v2_dev}
import com.digitalasset.daml.lf.language.{Ast, LanguageVersion}
import org.scalatest.matchers.should.Matchers
import org.scalatest.prop.TableDrivenPropertyChecks
import org.scalatest.wordspec.AnyWordSpec

import java.io.File
import scala.language.implicitConversions

class DamlLfEncoderTest extends AnyWordSpec with Matchers with TableDrivenPropertyChecks {

  "dar generated by encoder" should {

    "be readable" in {

      val sharedModules = Set[DottedName](
        "UnitMod",
        "BoolMod",
        "Int64Mod",
        "TextMod",
        "DateMod",
        "TimestampMod",
        "ListMod",
        "PartyMod",
        "RecordMod",
        "VariantMod",
        "BuiltinMod",
        "TemplateMod",
        "OptionMod",
        "EnumMod",
        "NumericMod",
        "AnyMod",
        "SynonymMod",
        "GenMapMod",
        "ExceptionMod",
        "InterfaceMod",
        "InterfaceMod0",
        "TextMapMod",
        "LedgerTimeMod",
      )
      val modules_2_1 = sharedModules ++ Set[DottedName]("InterfaceUnsafeFromMod")
      val modules_2_2 = sharedModules
      val modules_2_3 = sharedModules ++ Set[DottedName](
        "TemplateWithKeyMod"
      )
      val modules_2_dev = sharedModules ++ Set[DottedName](
        "BigNumericMod",
        "InterfaceExtMod",
        "TemplateWithKeyMod",
        "UnpackMod",
        "Uint256Mod",
        "DA.Types", // stable package
      )

      val stableModules = Set[DottedName](
        "DA.Exception.ArithmeticError",
        "DA.Exception.AssertionFailed",
        "DA.Exception.GeneralError",
        "DA.Exception.PreconditionFailed",
        "DA.Internal.Erased",
        "DA.Internal.NatSyn",
        "DA.Internal.PromotedText",
        "DA.Types",
        "GHC.Prim",
        "GHC.Tuple",
        "GHC.Types",
        "GHC.Stack.Types",
        "DA.Action.State.Type",
        "DA.Date.Types",
        "DA.Internal.Any",
        "DA.Internal.Down",
        "DA.Internal.Fail.Types",
        "DA.Internal.Interface.AnyView.Types",
        "DA.Internal.Template",
        "DA.Logic.Types",
        "DA.Monoid.Types",
        "DA.NonEmpty.Types",
        "DA.Random.Types",
        "DA.Semigroup.Types",
        "DA.Set.Types",
        "DA.Stack.Types",
        "DA.Time.Types",
        "DA.Validation.Types",
      )

      val versions = Table(
        "versions" -> "modules",
        v2_1 -> modules_2_1,
        v2_2 -> modules_2_2,
        v2_3 -> modules_2_3,
        v2_dev -> modules_2_dev,
      )

      forEvery(versions) { (version, expectedModules) =>
        val darFile =
          new java.io.File(getClass.getClassLoader.getResource(s"test-${version.pretty}.dar").toURI)
        val dar = DarDecoder.readArchiveFromFile(darFile)

        dar shouldBe a[Right[?, ?]]

        val findModules = dar.toOption.toList.flatMap(getNonEmptyModules).toSet

        (findModules diff expectedModules) diff stableModules shouldBe Set()
        (expectedModules diff findModules) diff stableModules shouldBe Set()

      }
    }

  }

  private def getNonEmptyModules(dar: Dar[(PackageId, Ast.Package)]): Seq[ModuleName] =
    for {
      (_, pkg) <- dar.all
      mod <- pkg.modules.values.toSeq
      if mod.definitions.nonEmpty || mod.templates.nonEmpty
    } yield mod.name

  "BuiltinMod" should {

    val builtinMod = ModuleName.assertFromString("BuiltinMod")

    "contains all builtins " in {
      forEvery(
        Table("version", LanguageVersion.allLfVersions.filter(LanguageVersion.v2_dev < _)*)
      ) { version =>
        // Construct the file path dynamically using the helper and the version
        val darFile =
          new java.io.File(getClass.getClassLoader.getResource(s"test-${version.pretty}.dar").toURI)

        val Right(dar) = DarDecoder.readArchiveFromFile(darFile)

        val (_, mainPkg) = dar.main
        val builtinInModule = mainPkg
          .modules(builtinMod)
          .definitions
          .values
          .collect { case Ast.DValue(_, Ast.EBuiltinFun(builtin)) => builtin }
          .toSet
        val builtinsInVersion = DecodeV2.builtinFunctionInfos.collect {
          case DecodeV2.BuiltinFunctionInfo(_, builtin, minVersion, maxVersion, _, _)
              if minVersion <= version && maxVersion.forall(version < _) =>
            builtin
        }.toSet

        val missingBuiltins = builtinsInVersion -- builtinInModule
        assert(missingBuiltins.isEmpty, s", missing builtin(s) in BuiltinMod")
        val unexpectedBuiltins = builtinInModule -- builtinsInVersion
        assert(unexpectedBuiltins.isEmpty, s", unexpected builtin(s) in BuiltinMod")
      }
    }
  }

  private implicit def toDottedName(s: String): DottedName =
    DottedName.assertFromString(s)

  // Helper to get the directory from the system property
  def getDarDirectory: File = {
    val path = sys.props
      .get("daml.test.darDir")
      .getOrElse(
        throw new RuntimeException(
          "System property 'daml.test.darDir' not set. Are you running from sbt with 'Test / fork := true'?"
        )
      )
    new File(path)
  }

}

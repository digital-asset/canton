#!/usr/bin/env python3
import argparse
import glob
import html
import json
import os
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

# GitHub renders at most 1 MiB per step summary and drops anything larger. Stay
# comfortably under that so a shard with many failures still produces a valid
# summary rather than a rejected oversized one, the remainder stays in the
# uploaded artifact.
SUMMARY_BUDGET_BYTES = 900_000
# Headroom kept below the budget for the trailing "and N more" line when the
# first detail block has to be byte-truncated to fit.
SUMMARY_TRAILER_RESERVE_BYTES = 256
# Default heading for the not-passed list. Used by the post-rerun (merged) caller.
# The pre-rerun caller passes its own so a recovered flaky is not mislabeled.
DEFAULT_NOT_PASSED_TITLE = "Not passed tests (after rerun)"


def parse_args():
    parser = argparse.ArgumentParser(
        description="Summarize JUnit XML results for a single test shard and optionally write JSON output."
    )
    parser.add_argument(
        "--shard-index", type=int, required=True, help="Index of the current shard."
    )
    parser.add_argument(
        "--total-shards", type=int, required=True, help="Total number of shards in the test run."
    )
    parser.add_argument(
        "--junit-glob", required=True, help="Glob pattern used to find JUnit XML files."
    )
    parser.add_argument(
        "--summary-path",
        default="",
        help="Path to append markdown summary to. If empty, uses GITHUB_STEP_SUMMARY when set.",
    )
    parser.add_argument(
        "--json-output",
        default="",
        help="Optional path to write JSON summary payload.",
    )
    parser.add_argument(
        "--rerun-metadata-json",
        default="",
        help="Optional path to rerun metadata JSON generated by merge_junit_results.py.",
    )
    parser.add_argument(
        "--limit",
        type=int,
        default=100,
        help="Maximum number of not-passed tests to detail in the markdown summary.",
    )
    parser.add_argument(
        "--trace-lines",
        type=int,
        default=60,
        help="Maximum number of failure-output lines to show per test before truncating.",
    )
    parser.add_argument(
        "--section-title",
        default=DEFAULT_NOT_PASSED_TITLE,
        help=(
            "Heading for the not-passed list. Defaults to the post-rerun wording. The "
            "pre-rerun caller overrides it so first-run failures are not mislabeled as "
            "surviving the rerun."
        ),
    )
    return parser.parse_args()


def failure_text(elem):
    """Full failure/error text for a testcase child element.

    The `message` attribute holds the one-line summary (typically the assertion),
    the element body holds the stack trace. Joining both reproduces what the CI
    Tests tab used to show for a failed test.
    """
    message = (elem.get("message") or "").strip()
    body = (elem.text or "").strip()
    if message and body:
        return message + "\n" + body
    return message or body


def gather_results(paths):
    passed = 0
    failures = 0
    errors = 0
    skipped = 0
    parse_errors = 0
    failed_tests = []
    errored_tests = []
    not_passed_tests = []
    not_passed_classes = []
    not_passed_details = {}

    for path in paths:
        try:
            root = ET.parse(path).getroot()
        except ET.ParseError:
            parse_errors += 1
            continue

        for testcase in root.findall(".//testcase"):
            classname = testcase.attrib.get("classname", "")
            name = testcase.attrib.get("name", "")
            full_name = f"{classname}.{name}" if classname else name

            error_elem = testcase.find("error")
            failure_elem = testcase.find("failure")

            if error_elem is not None:
                errors += 1
                if full_name:
                    errored_tests.append(full_name)
                    not_passed_tests.append(full_name)
                    not_passed_details.setdefault(full_name, failure_text(error_elem))
                if classname:
                    not_passed_classes.append(classname)
            elif failure_elem is not None:
                failures += 1
                if full_name:
                    failed_tests.append(full_name)
                    not_passed_tests.append(full_name)
                    not_passed_details.setdefault(full_name, failure_text(failure_elem))
                if classname:
                    not_passed_classes.append(classname)
            elif testcase.find("skipped") is not None:
                skipped += 1
            else:
                passed += 1

    total = passed + failures + errors + skipped
    unique_failed = len(dict.fromkeys(failed_tests))
    unique_errors = len(dict.fromkeys(errored_tests))
    unique_not_passed = list(dict.fromkeys(not_passed_tests))
    unique_not_passed_classes = list(dict.fromkeys(not_passed_classes))

    return {
        "passed": passed,
        "failures": failures,
        "failures_unique": unique_failed,
        "errors": errors,
        "errors_unique": unique_errors,
        "skipped": skipped,
        "parse_errors": parse_errors,
        "total": total,
        "not_passed_classes": unique_not_passed_classes,
        "not_passed_tests": unique_not_passed,
        # Full failure text per test, so the aggregate summary can render traces, not just names.
        "not_passed_details": not_passed_details,
    }


def fence_for(text):
    """Return a backtick fence long enough that `text` cannot close it early."""
    fence = "```"
    while fence in text:
        fence += "`"
    return fence


def render_detail(full_name, text, trace_lines, max_bytes=None):
    """Render one collapsible block with the test name and its failure output.

    GitHub only renders markdown inside `<details>` when a blank line separates
    the HTML tags from the inner block, so keep a blank line after `</summary>`
    and before `</details>`, otherwise the fenced code block is not rendered.

    When `max_bytes` is set, the failure text is byte-truncated so the rendered
    block fits within that budget. `trace_lines` caps the line count but not the
    byte size (a single line can be arbitrarily long), so this is the only guard
    that keeps one pathological block from pushing the whole summary over the
    limit and getting it dropped.
    """
    header = f"<details><summary>❌ {html.escape(full_name)}</summary>"
    if not text:
        return "\n".join(
            [header, "", "(no failure output captured, see the artifact)", "", "</details>"]
        )
    output_lines = text.splitlines()
    shown = output_lines[:trace_lines]
    hidden = len(output_lines) - len(shown)
    if hidden > 0:
        shown.append(f"... ({hidden} more lines, full trace in the artifact)")
    body_text = "\n".join(shown)
    fence = fence_for(body_text)
    if max_bytes is not None:
        marker = "... (truncated, full trace in the artifact)"
        # Everything except the body: header, blank lines, both fences, the
        # truncation marker and the closing tag. Budget the body against the rest.
        scaffold = "\n".join([header, "", fence, "", marker, fence, "", "</details>"])
        allowed = max_bytes - len(scaffold.encode("utf-8"))
        encoded = body_text.encode("utf-8")
        if allowed < len(encoded):
            body_text = encoded[: max(allowed, 0)].decode("utf-8", errors="ignore")
            return "\n".join([header, "", fence, body_text, marker, fence, "", "</details>"])
    return "\n".join([header, "", fence, body_text, fence, "", "</details>"])


def cap_detail_text(text, trace_lines):
    """Line-cap failure text for the persisted JSON, keeping the shard state small. The aggregate applies the byte budget."""
    if not text:
        return text
    output_lines = text.splitlines()
    if len(output_lines) <= trace_lines:
        return text
    hidden = len(output_lines) - trace_lines
    shown = output_lines[:trace_lines]
    shown.append(f"... ({hidden} more lines, full trace in the artifact)")
    return "\n".join(shown)


def build_summary(args, files, results, rerun_metadata=None):
    failures_unique = results.get("failures_unique", results["failures"])
    errors_unique = results.get("errors_unique", results["errors"])
    details = results.get("not_passed_details", {})

    lines = []
    lines.append(f"## Test summary (shard {args.shard_index}/{args.total_shards})")
    lines.append("")
    lines.append(f"- JUnit files found: {len(files)}")
    lines.append(f"- Total: {results['total']}")
    lines.append(f"- Passed: {results['passed']}")
    lines.append(f"- Failed: {results['failures']} ({failures_unique} unique)")
    lines.append(f"- Errors: {results['errors']} ({errors_unique} unique)")
    lines.append(f"- Skipped: {results['skipped']}")
    if rerun_metadata is not None:
        rerun_used = bool(rerun_metadata.get("rerun_used", False))
        rerun_classes = rerun_metadata.get("rerun_classes", [])
        if rerun_used:
            lines.append(f"- Failed-only rerun: yes ({len(rerun_classes)} classes)")
        else:
            lines.append("- Failed-only rerun: no")
    if results["parse_errors"]:
        lines.append(f"- XML parse errors: {results['parse_errors']}")
    lines.append("")

    if rerun_metadata is not None and rerun_metadata.get("rerun_used", False):
        rerun_classes = rerun_metadata.get("rerun_classes", [])
        if rerun_classes:
            shown = rerun_classes[:20]
            lines.append("### Rerun classes")
            lines.append(
                f"<details><summary>Show classes rerun after first attempt ({len(rerun_classes)}, shown {len(shown)})</summary>"
            )
            lines.append("")
            for class_name in shown:
                lines.append(f"- {html.escape(class_name)}")
            if len(rerun_classes) > len(shown):
                lines.append(f"- and {len(rerun_classes) - len(shown)} more")
            lines.append("")
            lines.append("</details>")
            lines.append("")

    lines.append(f"### {getattr(args, 'section_title', DEFAULT_NOT_PASSED_TITLE)}")
    not_passed = results["not_passed_tests"]
    if not not_passed:
        lines.append("- none")
        return "\n".join(lines) + "\n"

    total_not_passed = len(not_passed)
    lines.append(f"Failed or errored tests: {total_not_passed}")
    lines.append("")

    running = len(("\n".join(lines) + "\n").encode("utf-8"))
    shown_count = 0
    for name in not_passed[: args.limit]:
        block = render_detail(name, details.get(name, ""), args.trace_lines)
        block_bytes = len(block.encode("utf-8")) + 1
        if running + block_bytes > SUMMARY_BUDGET_BYTES:
            if shown_count == 0:
                # Even the first block overflows the budget (a single very long
                # failure line is not bounded by --trace-lines). Byte-truncate it
                # so the summary still renders instead of GitHub dropping it whole,
                # then defer the rest to the artifact.
                budget = SUMMARY_BUDGET_BYTES - running - SUMMARY_TRAILER_RESERVE_BYTES
                block = render_detail(
                    name, details.get(name, ""), args.trace_lines, max_bytes=budget
                )
                lines.append(block)
                shown_count += 1
            break
        lines.append(block)
        running += block_bytes
        shown_count += 1

    remaining = total_not_passed - shown_count
    if remaining > 0:
        lines.append("")
        lines.append(f"- and {remaining} more, full details in the artifact")

    return "\n".join(lines) + "\n"


def main():
    args = parse_args()
    files = sorted(glob.glob(args.junit_glob, recursive=True))
    files = [path for path in files if os.path.isfile(path)]

    rerun_metadata = None
    if args.rerun_metadata_json:
        rerun_path = Path(args.rerun_metadata_json)
        if rerun_path.is_file():
            with open(rerun_path, encoding="utf-8") as src:
                rerun_metadata = json.load(src)

    results = gather_results(files)
    summary = build_summary(args, files, results, rerun_metadata=rerun_metadata)

    print(summary)

    summary_path = args.summary_path or os.environ.get("GITHUB_STEP_SUMMARY", "")
    if summary_path:
        with open(summary_path, "a", encoding="utf-8") as out:
            out.write(summary)

    if args.json_output:
        json_output_path = Path(args.json_output)
        json_output_path.parent.mkdir(parents=True, exist_ok=True)
        payload = build_json_payload(args, files, results, rerun_metadata)
        with open(json_output_path, "w", encoding="utf-8") as out:
            json.dump(payload, out, ensure_ascii=True, indent=2)


def build_json_payload(args, files, results, rerun_metadata):
    # Line-capped details in the JSON let the aggregate render traces, the full traces stay in the test-summary.md artifact.
    details = results.get("not_passed_details", {})
    results_for_json = {key: value for key, value in results.items() if key != "not_passed_details"}
    results_for_json["not_passed_details"] = {
        name: cap_detail_text(text, args.trace_lines) for name, text in details.items()
    }
    payload = {
        "shard_index": args.shard_index,
        "total_shards": args.total_shards,
        "junit_files": len(files),
        "results": results_for_json,
    }
    if rerun_metadata is not None:
        payload["rerun"] = rerun_metadata
    return payload


